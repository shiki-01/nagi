/// 1 文字の入力を、記号の表のキー（ASCII 記号）に読み替える。ローマ字入力で `(` が `（` に
/// なるように、日本語入力中の記号は全角や日本語の約物で入力されるため、全角の ASCII 記号と
/// 一部の約物（`。` `、` `「` `」` `・` `ー` `〜`）も同じ表で引く。ASCII 記号以外は `None`
fn ascii_key(c: char) -> Option<char> {
    let key = match c {
        '。' => '.',
        '、' => ',',
        '「' => '[',
        '」' => ']',
        '・' => '/',
        'ー' => '-',
        '〜' => '~',
        '\u{ff01}'..='\u{ff5e}' => char::from_u32(c as u32 - 0xfee0)?,
        _ => c,
    };
    key.is_ascii_punctuation().then_some(key)
}

/// [`SymbolRewriter`] の識別子
pub const SYMBOL_REWRITER_ID: &str = "symbols";

/// 記号の変換（読み → 記号、1 文字の ASCII 記号 → 装飾された記号）
#[derive(Debug, Clone, Copy, Default)]
pub struct SymbolRewriter;

impl Rewriter for SymbolRewriter {
    fn id(&self) -> &str {
        SYMBOL_REWRITER_ID
    }

    fn rewrite(&self, reading: &str) -> Vec<String> {
        let mut chars = reading.chars();
        let table: &[&str] = match (chars.next(), chars.next()) {
            (Some(c), None) if ascii_key(c).is_some() => ASCII_TABLE
                .iter()
                .find(|(key, _)| Some(*key) == ascii_key(c))
                .map(|(_, v)| *v)
                .unwrap_or(&[]),
            (Some(_), _) => READING_TABLE
                .iter()
                .find(|(key, _)| *key == reading)
                .map(|(_, v)| *v)
                .unwrap_or(&[]),
            (None, _) => &[],
        };
        let mut out: Vec<String> = Vec::new();
        for s in table {
            if *s != reading && !out.iter().any(|o| o == s) {
                out.push((*s).to_string());
            }
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rw(s: &str) -> Vec<String> {
        SymbolRewriter.rewrite(s)
    }

    #[test]
    fn reading_entries() {
        let kakko = rw("かっこ");
        assert_eq!(kakko[0], "「」");
        assert!(kakko.contains(&"【】".to_string()));
        assert!(kakko.contains(&"()".to_string()));
        assert_eq!(rw("まる")[..3], ["。", "○", "◯"]);
        assert_eq!(rw("てん")[0], "、");
        assert_eq!(rw("さんかく"), ["△", "▲", "▽", "▼"]);
        assert_eq!(rw("やじるし")[0], "→");
        assert_eq!(rw("はーと"), ["♡", "♥"]);
        assert_eq!(rw("ハート"), ["♡", "♥"]);
        assert_eq!(rw("ゆうびん"), ["〒"]);
        assert_eq!(rw("かける"), ["×"]);
        assert_eq!(rw("わる"), ["÷"]);
        assert_eq!(rw("いこーる"), ["＝", "≒", "≠"]);
        assert!(!rw("きごう").is_empty());
    }

    #[test]
    fn ascii_entries() {
        assert_eq!(rw("(")[..3], ["（", "「", "『"]);
        assert_eq!(rw(")")[0], "）");
        assert_eq!(rw("."), ["。", "．", "…"]);
        assert_eq!(rw("-"), ["ー", "－", "―", "‐"]);
        assert!(rw("\\").contains(&"¥".to_string()));
        assert!(rw("\"").contains(&"“".to_string()));
        // 入力そのものの表記は含めない
        assert!(!rw("'").contains(&"'".to_string()));
        // ローマ字入力で記号が全角・約物になった読み（`(` → `（`）も同じ表で引く
        assert_eq!(rw("（")[..2], ["「", "『"]);
        assert!(!rw("（").contains(&"（".to_string()));
        assert_eq!(rw("。"), ["．", "…"]);
        assert!(rw("、").contains(&"，".to_string()));
    }

    #[test]
    fn no_duplicates_in_each_entry() {
        let all = READING_TABLE
            .iter()
            .map(|(k, _)| k.to_string())
            .chain(ASCII_TABLE.iter().map(|(k, _)| k.to_string()));
        for key in all {
            let out = rw(&key);
            let mut seen = std::collections::HashSet::new();
            assert!(out.iter().all(|s| seen.insert(s.clone())), "{key}: {out:?}");
        }
    }

    #[test]
    fn rejects_multichar_and_alnum() {
        // 複数文字・英数字・未登録の読みでは出さない
        assert!(rw("()").is_empty());
        assert!(rw("1+2").is_empty());
        assert!(rw("a").is_empty());
        assert!(rw("1").is_empty());
        assert!(rw("きょう").is_empty());
        assert!(rw("").is_empty());
    }
}
