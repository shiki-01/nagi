/// 1 文字の ASCII 記号 → 装飾・変形の候補（開きかっこは対応する閉じかっこを別の記号で持つ）
const ASCII_TABLE: &[(char, &[&str])] = &[
    ('(', &["（", "「", "『", "【", "〔", "〈", "《", "［", "｛"]),
    (')', &["）", "」", "』", "】", "〕", "〉", "》", "］", "｝"]),
    ('[', &["［", "「", "『", "【", "〔"]),
    (']', &["］", "」", "』", "】", "〕"]),
    ('{', &["｛", "「", "『", "【"]),
    ('}', &["｝", "」", "』", "】"]),
    ('<', &["＜", "〈", "《", "≦", "≪"]),
    ('>', &["＞", "〉", "》", "≧", "≫"]),
    ('.', &["。", "．", "…"]),
    (',', &["、", "，"]),
    ('!', &["！", "‼", "❗"]),
    ('?', &["？", "⁇", "❓"]),
    ('~', &["〜", "～"]),
    ('-', &["ー", "－", "―", "‐"]),
    ('/', &["／", "・", "÷"]),
    (':', &["：", "∶"]),
    (';', &["；"]),
    ('=', &["＝", "≒", "≠"]),
    ('+', &["＋", "±"]),
    ('*', &["＊", "×", "★", "☆"]),
    ('\'', &["’", "‘", "＇"]),
    ('"', &["”", "“", "「", "」", "＂"]),
    ('@', &["＠"]),
    ('#', &["＃", "♯"]),
    ('&', &["＆"]),
    ('%', &["％", "‰"]),
    ('\\', &["＼", "¥"]),
    ('^', &["＾"]),
    ('_', &["＿"]),
    ('|', &["｜", "¦"]),
    ('$', &["＄", "¥", "￥"]),
    ('`', &["｀", "‘"]),
];

/// 1 文字の入力を、記号の表のキー（ASCII 記号）に読み替える。ローマ字入力で `(` が `（` に
/// なるように、日本語入力中の記号は全角や日本語の約物で入力されるため、全角の ASCII 記号と
/// 一部の約物（`。` `、` `「` `」` `・` `ー` `〜`）も同じ表で引く。ASCII 記号以外は `None`
fn ascii_key(c: char) -> Option<char> {
    let key = match c {
        '。' => '.',
        '、' => ',',
        '「' => '[',
        '」' => ']',
        '・' => '/',
        'ー' => '-',
        '〜' => '~',
        '\u{ff01}'..='\u{ff5e}' => char::from_u32(c as u32 - 0xfee0)?,
        _ => c,
    };
    key.is_ascii_punctuation().then_some(key)
}

/// 読みの表に登録された読みの数（診断・テスト用）
pub fn reading_count() -> usize {
    READING_GROUPS.iter().map(|(keys, _)| keys.len()).sum()
}

/// [`SymbolRewriter`] の識別子
pub const SYMBOL_REWRITER_ID: &str = "symbols";

/// 記号の変換（読み → 記号、1 文字の ASCII 記号 → 装飾された記号）
#[derive(Debug, Clone, Copy, Default)]
pub struct SymbolRewriter;

impl Rewriter for SymbolRewriter {
    fn id(&self) -> &str {
        SYMBOL_REWRITER_ID
    }

    fn rewrite(&self, reading: &str) -> Vec<String> {
        let mut chars = reading.chars();
        let table: &[&str] = match (chars.next(), chars.next()) {
            (Some(c), None) if ascii_key(c).is_some() => ASCII_TABLE
                .iter()
                .find(|(key, _)| Some(*key) == ascii_key(c))
                .map(|(_, v)| *v)
                .unwrap_or(&[]),
            (Some(_), _) => READING_GROUPS
                .iter()
                .find(|(keys, _)| keys.contains(&reading))
                .map(|(_, v)| *v)
                .unwrap_or(&[]),
            (None, _) => &[],
        };
        let mut out: Vec<String> = Vec::new();
        for s in table {
            if *s != reading && !out.iter().any(|o| o == s) {
                out.push((*s).to_string());
            }
        }
        out
    }
}

