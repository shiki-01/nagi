#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn array_lengths() {
        assert_eq!(HIRAGANA_16.len(), 16 * 16);
        assert_eq!(HIRAGANA_32.len(), 32 * 32);
        assert_eq!(ROMAN_16.len(), 16 * 16);
        assert_eq!(ROMAN_32.len(), 32 * 32);
    }

    /// 四隅は透明で、中央付近に文字の画素がある。
    fn check(alpha: &[u8], size: usize) {
        let at = |x: usize, y: usize| alpha[y * size + x];
        for (x, y) in [(0, 0), (size - 1, 0), (0, size - 1), (size - 1, size - 1)] {
            assert_eq!(at(x, y), 0, "corner ({x},{y})");
        }
        let (lo, hi) = (size / 4, size * 3 / 4);
        let center_max = (lo..hi)
            .flat_map(|y| (lo..hi).map(move |x| (x, y)))
            .map(|(x, y)| at(x, y))
            .max()
            .unwrap();
        assert_eq!(center_max, 255);
    }

    #[test]
    fn glyphs_are_centered_and_corners_clear() {
        check(&HIRAGANA_16, 16);
        check(&HIRAGANA_32, 32);
        check(&ROMAN_16, 16);
        check(&ROMAN_32, 32);
    }

    #[test]
    fn modes_differ() {
        assert_ne!(HIRAGANA_32[..], ROMAN_32[..]);
    }
}
