//! 色付きの図形ではなく文字の形（「あ」「A」）のアルファ画像を使う。
//! xtask 実行時にフォントを読まず OS 非依存にするため、アルファ値（8bit・行優先）を埋め込む。
//!
//! 生成方法（Python 3 + Pillow 12.3、IPAゴシック `ipag.ttf`。リポジトリには入れていない）:
//! - 出力サイズ（16 / 32）の 16 倍の正方形キャンバスに、白で文字を描く
//! - フォントサイズはキャンバスの「あ」0.82 倍・「A」1.0 倍、太らせるため `stroke_width` はキャンバスの 1.8%
//! - `textbbox`（stroke 込み）で字形の外接矩形を求め、キャンバス中央に置く
//! - `Image.BOX` で出力サイズへ縮小し、グレースケール値をそのままアルファにする
//!
//! 描画時の RGB は黒（0,0,0）。

