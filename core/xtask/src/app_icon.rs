//! - フォントサイズはキャンバスの 0.60 倍、`stroke_width` はキャンバスの 1.2%（わずかに太らせる）
//! - `textbbox`（stroke 込み）で字形の外接矩形を求め、キャンバス中央に置く
//! - `Image.BOX` で 128px へ縮小し、グレースケール値をそのままアルファにする

