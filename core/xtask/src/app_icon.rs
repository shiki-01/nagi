    /// icns を (種別, PNG データ) の列に分解する。
    fn parse_icns(icns: &[u8]) -> Vec<([u8; 4], &[u8])> {
        assert_eq!(&icns[..4], b"icns");
        let total = u32::from_be_bytes(icns[4..8].try_into().unwrap()) as usize;
        assert_eq!(total, icns.len());
        let mut o = 8;
        let mut entries = Vec::new();
        while o < icns.len() {
            let kind: [u8; 4] = icns[o..o + 4].try_into().unwrap();
            let len = u32::from_be_bytes(icns[o + 4..o + 8].try_into().unwrap()) as usize;
            entries.push((kind, &icns[o + 8..o + len]));
            o += len;
        }
        assert_eq!(o, icns.len());
        entries
    }

