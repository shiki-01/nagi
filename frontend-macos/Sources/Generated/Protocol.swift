/// `update_settings` のパラメータ
public struct UpdateSettingsParams: Codable {
	/// 変更のリスト（先頭から順に適用）
	public let changes: [SettingChange]

	public init(changes: [SettingChange]) {
		self.changes = changes
	}
}

/// `update_settings` の結果
public struct UpdateSettingsResult: Codable {
	/// 適用できたキー
	public let applied: [String]
	/// 適用できなかった項目（他の項目は適用済み）
	public let errors: [SettingError]
	/// 適用後の最新の状態
	public let snapshot: SettingsSnapshot

	public init(applied: [String], errors: [SettingError], snapshot: SettingsSnapshot) {
		self.applied = applied
		self.errors = errors
		self.snapshot = snapshot
	}
}

/// 12 キーの操作
public enum KeyGesture: String, Codable {
	/// タップ（行の先頭の文字。連続してもトグルしない。フリック入力用）
	case tap
	/// トグル入力のタップ（連続して同じキーを押すと、直前の文字を同じ行の次の文字に置き換える）
	case toggle
	/// 左フリック
	case flickLeft = "flick_left"
	/// 上フリック
	case flickUp = "flick_up"
	/// 右フリック
	case flickRight = "flick_right"
	/// 下フリック
	case flickDown = "flick_down"
}

/// 左右の方向
public enum TouchDirection: String, Codable {
	/// 左
	case left
	/// 右
	case right
}
