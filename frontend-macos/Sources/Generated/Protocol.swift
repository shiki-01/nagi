public struct SettingItem: Codable {
	/// ドット区切りの TOML パス（例: `conversion.sync_budget_ms`）
	public let key: String
	/// 表示グループ名（日本語）
	public let group: String
	/// 表示名（日本語）
	public let label: String
	/// 説明（日本語・1〜2 文）
	public let description: String
	/// 型
	public let kind: SettingKind
	/// 現在の有効値。`null` は「未指定でプロファイルが決める」項目（`conversion.beam_width` など）
	public let value: SettingValue?
	/// 既定値（`null` の意味は `value` と同じ）
	public let `default`: SettingValue?
	/// `config.toml` に明示指定があるか
	public let explicit: Bool
	/// 反映にエンジンの再起動が要るか
	public let requires_restart: Bool

	public init(key: String, group: String, label: String, description: String, kind: SettingKind, value: SettingValue?, default: SettingValue?, explicit: Bool, requires_restart: Bool) {
		self.key = key
		self.group = group
		self.label = label
		self.description = description
		self.kind = kind
		self.value = value
		self.default = `default`
		self.explicit = explicit
		self.requires_restart = requires_restart
	}
}

/// `get_settings` の結果
public struct SettingsSnapshot: Codable {
	/// 設定項目（表示順。同じ `group` が連続する）
	public let items: [SettingItem]
	/// 設定ファイルの構文が壊れている等で、値を読めなかった場合の理由（日本語）。
	/// このとき `items` の値はすべて既定値で、`update_settings` は書き込まない
	public let error: String?

	public init(items: [SettingItem], error: String?) {
		self.items = items
		self.error = error
	}
}

/// `get_status` の結果: メニューなどで「今どういう状態か・なぜか」を表示するための情報
public struct StatusResult: Codable {
	/// 現在の環境プロファイル（`quality` / `balanced` / `light` / `minimal`）
	public let profile: String
	/// そのプロファイルになった理由（日本語）
	public let profile_reason: String
	/// 変換バックエンド名（診断用）
	public let backend: String
	/// LLM を使っているか
	public let llm: Bool
	/// 学習が有効か（secure input 中などで一時停止していても、設定として有効なら true）
	public let learning: Bool
	/// 学習データの件数
	public let learned_entries: UInt32
	/// ユーザー辞書の語数
	public let user_dict_entries: UInt32
	/// 設定ファイルのパス（未解決なら None）
	public let config_path: String?
	/// 直近の設定読み込みに失敗して旧設定で動いているか
	public let config_error: Bool

	public init(profile: String, profile_reason: String, backend: String, llm: Bool, learning: Bool, learned_entries: UInt32, user_dict_entries: UInt32, config_path: String?, config_error: Bool) {
		self.profile = profile
		self.profile_reason = profile_reason
		self.backend = backend
		self.llm = llm
		self.learning = learning
		self.learned_entries = learned_entries
		self.user_dict_entries = user_dict_entries
		self.config_path = config_path
		self.config_error = config_error
	}
}

