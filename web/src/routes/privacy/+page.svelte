  <h2>1. 基本方針</h2>
  <p>
    Nagi は、あなたが入力した文章を、開発者や第三者のサーバーへ送信しません。
    かな漢字変換・学習・辞書の処理は、すべてお使いの端末の中で行います。
    開発者は、Nagi の利用を通じて個人情報を収集しません。
  </p>
  <p class="operator">
    提供者: <span class="legal">【要確認: 提供者名（個人開発者の氏名または屋号）】</span>
  </p>

  <h2>2. 収集する情報</h2>
  <p><strong>Nagi は、開発者のサーバーに送信される形で情報を収集しません。</strong></p>
  <ul>
    <li>入力した文字、変換の履歴、学習データ、ユーザー辞書、設定は、端末内にのみ保存されます。</li>
    <li>利用状況の解析（アナリティクス）、クラッシュ収集、広告の SDK は組み込んでいません。</li>
    <li>広告目的の追跡（トラッキング）は行いません。</li>
    <li>他社のアプリの入力内容や、位置情報、連絡先、写真などにアクセスしません。</li>
  </ul>
  <p>
    なお、TestFlight や App Store を通じて Apple が収集する情報（インストール数、クラッシュレポート、テスターのフィードバックなど）は、
    Apple のプライバシーポリシーに従って Apple が取り扱うもので、Nagi の開発者が入力内容を受け取ることはありません。
    TestFlight のクラッシュレポートやフィードバックの送信は、テスターが端末の設定で選択します。
  </p>

  <h2>3. 端末内に保存するもの</h2>
  <ul>
    <li>学習データ（変換で選んだ候補の履歴など。学習用ファイル）</li>
    <li>ユーザー辞書・スニペット、設定、作成・取り込んだキーボードレイアウト</li>
    <li>変換に使う辞書とモデルのファイル</li>
    <li>診断ログ（有効にした場合のみ。<a href="#diag">第 7 節</a>）</li>
  </ul>
  <p>
    iOS では、本体アプリとキーボード拡張が共有する領域（App Group）に保存されます。
    アプリを削除すると、これらのデータも端末から削除されます。
  </p>

  <h2>4. iOS の「フルアクセス」を求める理由</h2>
  <p>
    iOS のキーボード拡張は、「フルアクセスを許可」をオンにしないと、本体アプリが保存した辞書・モデルのファイルを読めません。
    Nagi が許可をお願いする理由は、<strong>辞書・モデルを共有領域から読み込むためだけ</strong>です。
  </p>
  <ul>
    <li>キーボードは通信を行いません。入力内容を外部へ送信しません。</li>
    <li>許可しない場合は、ひらがな・カタカナへの変換のみで動作します。入力した文字は失われません。</li>
    <li>許可はいつでも 設定 &gt; 一般 &gt; キーボード &gt; キーボード &gt; Nagi で切り替えられます。</li>
  </ul>
  <p class="note">
    iOS の仕組み上、フルアクセスを許可したキーボードは入力内容を外部へ送れる権限を持ちます。
    Nagi はその権限で入力内容を送信しません。コードは公開されているので、
    <a href={REPO_URL} rel="noopener">GitHub のリポジトリ</a>で確認できます。
  </p>

  <h2>5. ネットワーク通信</h2>
  <p>Nagi が通信するのは、次の場合に限ります。いずれも、入力内容を含みません。</p>
  <ul>
    <li>
      <strong>辞書・モデルの取得</strong>: ユーザーが取得の操作をしたときに、本体アプリが行います。
      通信先は <code>shiki-01.com</code> 配下、または辞書・モデルの配布元（例: Hugging Face）です。
      取得したファイルは SHA-256 で検証してから使います。
    </li>
    <li>
      <strong>データ（辞書・モデル）の更新確認</strong>: 本体アプリが行います。設定でいつでも無効にでき、
      確認は通知のみでダウンロードは自動で行いません。
    </li>
    <li>
      <strong>アプリ本体の更新</strong>: iOS では App Store / TestFlight が配信します。Nagi 自体は確認しません。
    </li>
  </ul>
  <p>
    更新確認で送られる情報は、確認先のサーバーへの接続に必要なもの（IP アドレス、User-Agent など、通常の通信で相手に伝わる情報）に限り、
    入力内容・学習データ・端末を識別する固有の ID は含みません。
    <span class="legal">【要確認: 確認先サーバーのアクセスログの保存期間と取り扱い】</span>
  </p>
  <p class="note">
    現在の TestFlight 版は、辞書とモデルをファイルから取り込む方式です。
    アプリ内からの取得・更新確認の機能は、提供する時点で上記の内容に従います。
  </p>

  <h2>6. 入力内容の取り扱い</h2>
  <ul>
    <li>ログに入力内容を残しません（開発者向けのデバッグビルドで、開発者が明示的に有効にした場合を除く）。</li>
    <li>パスワード欄など入力の秘匿が求められる欄では、学習・周辺テキストの取得・ログを停止します。</li>
    <li>メールアドレス・URL・数字などの欄では学習しない設定があります（設定で変更できます）。</li>
    <li>クリップボードは、貼り付けなどそれを必要とする機能をあなたが有効にしたときにのみ読み取ります。</li>
  </ul>

  <h2 id="diag">7. 診断ログ</h2>
  <ul>
    <li>
      不具合の調査のための診断ログを、端末内に記録する場合があります。TestFlight 期間中の暫定の機能で、
      正式版では既定で無効にする、または内容を限定する予定です。
    </li>
    <li>診断ログは端末内にのみ保存され、自動では送信されません。</li>
    <li>
      ログを開発者に共有するかどうかは、あなたが決めます。共有するには、アプリ内でコピーまたは書き出して、
      <a href={ISSUES_URL} rel="noopener">GitHub Issues</a> 等に自分で貼り付けます。
      共有する前に、内容を確認してください。TestFlight 版のログには、不具合の再現のために入力途中の文字列が含まれることがあります。
    </li>
    <li>ログはアプリ内からいつでも消去できます。</li>
  </ul>

  <h2>8. 学習データ・保存データの削除</h2>
  <ul>
    <li>
      <strong>学習データ</strong>: ホストアプリの「設定」タブにある「学習データをすべて削除」から削除できます
      （確認ダイアログが出ます）。
    </li>
    <li><strong>辞書・モデル</strong>: ファイルを削除して容量を空けられます。削除後は、読みをそのまま返す動作になります。</li>
    <li><strong>診断ログ</strong>: 入力テストタブから消去できます。</li>
    <li><strong>すべてのデータ</strong>: アプリを削除すると、端末内の Nagi のデータはすべて削除されます。</li>
  </ul>
  <p>開発者のサーバーにあなたのデータは存在しないため、開発者側での削除手続きは不要です。</p>

  <h2>9. このサイトについて</h2>
  <p>
    このサイトに、アクセス解析や広告、Cookie による追跡は設置していません。
    キーボード編集ページ（/custom-keyboard）で作成した内容は、お使いのブラウザの localStorage にのみ保存され、サーバーへは送信されません。
  </p>
  <p>
    <span class="legal">【要確認: ホスティング先決定後、そのサービスが記録するアクセスログ（IP アドレス等）の取り扱いを追記】</span>
  </p>

  <h2>10. 子どもの利用</h2>
  <p>
    Nagi は、子どもを対象にしたアプリではなく、年齢の確認や子どもからの情報収集を行いません。
    そもそも、利用者の個人情報を収集しません。
    <span class="legal">【要確認: 年齢区分の表記（App Store の年齢制限の回答との整合）】</span>
  </p>

